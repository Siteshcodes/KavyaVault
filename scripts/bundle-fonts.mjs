import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Regenerate only from the licensed, checked-in font sources. No downloads.
const names = ['NotoSerifDevanagari', 'NotoSerif', 'NotoSansSymbols2', 'NotoEmoji'];
const fonts = names.map(name => {
  const bytes = readFileSync(new URL(`../public/fonts/${name}-Regular.ttf`, import.meta.url));
  return { name, sha256: createHash('sha256').update(bytes).digest('hex'), base64: bytes.toString('base64') };
});
const license = readFileSync(new URL('../public/fonts/OFL.txt', import.meta.url), 'utf8');
const emojiLicense = readFileSync(new URL('../public/fonts/OFL-Emoji.txt', import.meta.url), 'utf8');
writeFileSync(new URL('../src/services/books/export/bundledFonts.js', import.meta.url),
  `// Generated by scripts/bundle-fonts.mjs. Font licenses: public/fonts/OFL*.txt.\nexport const fontSources = ${JSON.stringify(fonts)};\nexport const fontLicense = ${JSON.stringify(license)};\nexport const emojiLicense = ${JSON.stringify(emojiLicense)};\n`);
